"""Build locally hosted city photos and their runtime index.

Requires Pillow: python3 -m pip install Pillow
Usage: python3 scripts/build_city_images.py /tmp/sunseek-photo-sources --download
Without --download, uses only cached source images (no network).
The reviewed source/permission ledger is assets/city-images.json; do not discover
or replace images automatically. Each derivative keeps its source image license.
"""
import argparse
import hashlib
import io
import json
import subprocess
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('cache', type=Path)
    parser.add_argument('--download', action='store_true')
    args = parser.parse_args()
    args.cache.mkdir(parents=True, exist_ok=True)
    rows = json.loads((ROOT / 'assets/city-images.json').read_text())['images']
    (ROOT / 'assets/cities').mkdir(exist_ok=True)

    def build(row):
        source = args.cache / (row['id'] + '.source')
        if not source.exists():
            if not args.download:
                raise FileNotFoundError(f'{source}: supply source or use --download')
            temporary = source.with_suffix('.part')
            subprocess.run(['curl', '--fail', '--silent', '--show-error', '--location',
                            '--retry', '2', '--retry-delay', '3', '--max-time', '90',
                            row['download'], '--output', str(temporary)], check=True)
            with Image.open(temporary) as downloaded:
                downloaded.verify()
            temporary.replace(source)
        digest = hashlib.sha256(source.read_bytes()).hexdigest()
        if row.get('downloadSha256') and digest != row['downloadSha256']:
            raise ValueError(f"Source changed for {row['id']}; review before rebuilding")
        row['downloadSha256'] = digest
        row['outputs'] = {}
        with Image.open(source) as original:
            image = ImageOps.exif_transpose(original).convert('RGB')
            for key, width, height, budget in [('card', 640, 400, 50000), ('detail', 1280, 720, 150000)]:
                scale = min(1, image.width / width, image.height / height)
                size = (round(width * scale), round(height * scale))
                rendered = ImageOps.fit(image, size, method=Image.Resampling.LANCZOS)
                quality = 80
                while True:
                    encoded = io.BytesIO()
                    rendered.save(encoded, 'WEBP', quality=quality, method=6)
                    if encoded.tell() <= budget:
                        break
                    if quality > 55:
                        quality -= 5
                    else:
                        rendered = rendered.resize((round(rendered.width * .9), round(rendered.height * .9)), Image.Resampling.LANCZOS)
                (ROOT / row[key]).write_bytes(encoded.getvalue())
                row['outputs'][key] = {'width': rendered.width, 'height': rendered.height,
                                       'bytes': encoded.tell(),
                                       'sha256': hashlib.sha256(encoded.getvalue()).hexdigest()}
        print(f"Built {row['id']}", flush=True)

    failures = []
    def attempt(row):
        try:
            build(row)
        except Exception as error:
            failures.append(row['id'])
            print(f"Failed {row['id']}: {error}", flush=True)
    with ThreadPoolExecutor(max_workers=2) as pool:
        list(pool.map(attempt, rows))
    if failures:
        raise RuntimeError('Incomplete photos (rerun using the cache): ' + ', '.join(failures))
    (ROOT / 'assets/city-images.json').write_text(
        json.dumps({'version': 1, 'images': rows}, ensure_ascii=False, indent=2) + '\n')
    fields = ['kind', 'subject', 'alt', 'card', 'detail', 'position', 'author',
              'source', 'license', 'licenseUrl', 'changes']
    runtime = {row['id']: {key: row[key] for key in fields} for row in rows}
    (ROOT / 'assets/city-images.js').write_text(
        "// Generated by scripts/build_city_images.py; provenance: city-images.json\n"
        "window.SUNSEEK_CITY_IMAGES = " + json.dumps(runtime, ensure_ascii=False, indent=2) + ';\n')


if __name__ == '__main__':
    main()
